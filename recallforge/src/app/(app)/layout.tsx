import Link from "next/link";
import { Suspense } from "react";
import { Sparkles, Upload } from "lucide-react";
import { requireOnboardedUser, isAdmin } from "@/lib/auth/session";
import { db } from "@/lib/db";
import { getUsage } from "@/lib/billing/usage";
import { limitsFor } from "@/lib/billing/plans";
import { aiStatus } from "@/lib/ai";
import { Logo } from "@/components/logo";
import { Button } from "@/components/ui/button";
import { Progress } from "@/components/ui/misc";
import { MobileNav, SidebarNav } from "@/components/app/nav";
import { NotificationsBell } from "@/components/app/notifications-bell";
import { UserMenu } from "@/components/app/user-menu";
import { SearchBox } from "@/components/app/search-box";
import { VerifyBanner } from "@/components/app/verify-banner";
import { ThemeToggle } from "@/components/theme-toggle";
import { ReducedMotion } from "@/components/app/reduced-motion";

export default async function AppLayout({ children }: { children: React.ReactNode }) {
  const user = await requireOnboardedUser();
  const [usage, due] = await Promise.all([
    getUsage(user.id),
    db.card.count({ where: { userId: user.id, suspended: false, state: { not: "NEW" }, due: { lte: new Date() }, deck: { archived: false } } }),
  ]);
  const limits = limitsFor(user.plan);
  const ai = aiStatus();
  const cardPct = (usage.cardsGenerated / limits.cardsPerPeriod) * 100;
  return (
    <div className="min-h-screen lg:grid lg:grid-cols-[248px_1fr]">
      <ReducedMotion enabled={user.reducedMotion} />
      <aside className="sticky top-0 hidden h-screen flex-col border-r border-border bg-surface px-3 py-4 lg:flex">
        <Logo href="/dashboard" className="mb-6 px-2" />
        <SidebarNav dueCount={due} />
        <div className="mt-auto space-y-3">
          <Link href="/settings/billing" className="block rounded-xl border border-border p-3 text-xs hover:bg-surface-2">
            <div className="mb-1.5 flex justify-between text-muted">
              <span>AI cards this period</span>
              <span className="tabular-nums">
                {usage.cardsGenerated.toLocaleString()} / {limits.cardsPerPeriod.toLocaleString()}
              </span>
            </div>
            <Progress value={cardPct} tone={cardPct > 90 ? "danger" : cardPct > 70 ? "warning" : "primary"} label="AI card usage" />
            <div className="mt-2 flex justify-between text-muted">
              <span>Documents</span>
              <span className="tabular-nums">
                {usage.documents} / {limits.documentsPerPeriod}
              </span>
            </div>
          </Link>
          {user.plan === "FREE" && (
            <Button asChild variant="subtle" className="w-full">
              <Link href="/pricing">
                <Sparkles /> Upgrade to Pro
              </Link>
            </Button>
          )}
        </div>
      </aside>
      <div className="flex min-w-0 flex-col">
        {!user.emailVerifiedAt && <VerifyBanner />}
        {!ai.configured && (
          <div role="alert" className="border-b border-danger/30 bg-danger-soft px-4 py-2 text-center text-sm">
            AI generation is unavailable: {ai.message} Uploads are saved and will process once it&apos;s configured.
          </div>
        )}
        {ai.isMock && <div className="border-b border-border bg-surface-2 px-4 py-1.5 text-center text-xs text-muted">Development mode: using the offline mock AI provider. Cards are generated by simple text heuristics.</div>}
        <header className="sticky top-0 z-30 flex h-14 items-center gap-3 border-b border-border bg-bg/90 px-4 backdrop-blur sm:px-6">
          <Logo href="/dashboard" className="lg:hidden [&>span]:hidden sm:[&>span]:inline" />
          <Suspense>
            <SearchBox className="hidden max-w-md flex-1 sm:block" />
          </Suspense>
          <div className="ml-auto flex items-center gap-1.5">
            <Button asChild size="sm" className="hidden sm:inline-flex">
              <Link href="/upload">
                <Upload /> Upload
              </Link>
            </Button>
            <ThemeToggle />
            <NotificationsBell />
            <UserMenu name={user.name} email={user.email} plan={user.plan} admin={isAdmin(user)} />
          </div>
        </header>
        <main id="main" className="mx-auto w-full max-w-6xl flex-1 px-4 pb-28 pt-6 sm:px-6 lg:pb-12">
          {children}
        </main>
      </div>
      <MobileNav dueCount={due} />
    </div>
  );
}
